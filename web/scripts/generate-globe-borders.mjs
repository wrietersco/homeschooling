// Codegen: build the globe's country-border dataset from Natural Earth 110m
// (public domain, via the world-atlas package) keyed by our gazetteer's ISO2
// codes. Land features that are not sovereign countries in the gazetteer
// (Antarctica, Greenland, …) are kept under the reserved "_other" key so the
// globe still draws them. Run: node scripts/generate-globe-borders.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { feature } from "topojson-client";
import { slugName, countries } from "../../functions/lib/wikidoGazetteer.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const topo = JSON.parse(readFileSync(path.join(root, "node_modules/world-atlas/countries-110m.json"), "utf8"));
const geo = feature(topo, topo.objects.countries);

// Natural Earth display names that don't slug-match the gazetteer name.
const NAME_ALIASES = {
  "united states of america": "us",
  "dem rep congo": "cd",
  "democratic republic of the congo": "cd",
  congo: "cg",
  "republic of the congo": "cg",
  turkey: "tr",
  "czech rep": "cz",
  "czech republic": "cz",
  "bosnia and herz": "ba",
  "dominican rep": "do",
  "eq guinea": "gq",
  "central african rep": "cf",
  "s sudan": "ss",
  "solomon is": "sb",
  "cote d ivoire": "ci",
  "ivoire cote": "ci",
  eswatini: "sz",
  swaziland: "sz",
  macedonia: "mk",
  "north macedonia": "mk",
  "united kingdom of great britain and northern ireland": "gb",
  korea: "kr",
  "south korea": "kr",
  "dem rep korea": "kp",
  "north korea": "kp",
  "lao pdr": "la",
  laos: "la",
  "myanmar burma": "mm",
  burma: "mm",
  "timor leste": "tl",
  "east timor": "tl",
  "cabo verde": "cv",
  "cape verde": "cv",
  "sao tome and principe": "st",
  palestine: "ps",
  "west bank": "ps",
  "vatican city": "va",
  micronesia: "fm",
  "federated states of micronesia": "fm",
  "marshall is": "mh",
  "marshall islands": "mh",
  "cayman is": null,
};

const norm = (s) => slugName(s).replace(/-/g, " ").trim();
const byName = new Map(countries.map((c) => [norm(c.name), c.id]));

const out = {};
const other = [];
const matchedNames = new Set();
const unmatchedCountries = new Set(countries.map((c) => c.id));

const round = (n) => Math.round(n * 100) / 100;
const ring = (r) => r.map(([lng, lat]) => [round(lng), round(lat)]);

for (const f of geo.features) {
  const polys =
    f.geometry.type === "Polygon"
      ? [f.geometry.coordinates]
      : f.geometry.type === "MultiPolygon"
        ? f.geometry.coordinates
        : [];
  const shapes = polys.map((p) => p.map(ring));
  const name = norm(f.properties?.name);
  const alias = NAME_ALIASES[name];
  const iso2 = alias !== undefined ? alias : byName.get(name);
  if (iso2) {
    out[iso2] = (out[iso2] || []).concat(shapes);
    matchedNames.add(name);
    unmatchedCountries.delete(iso2);
  } else {
    other.push(...shapes);
  }
}

// Sovereign land that Natural Earth 110m does not carry (microstates and tiny
// island nations) — pins still show for them; only their outline is absent.
const TINY_NATIONS = new Set(["mc", "sm", "va", "li", "mt", "sg", "bh", "mv", "bb", "sc", "km", "mu", "tv", "nr", "pw", "mh", "ki", "to", "ws", "fm"]);
const gaps = [...unmatchedCountries].filter((id) => !TINY_NATIONS.has(id));

const payload = { ...out, _other: other };
const file = `// GENERATED by scripts/generate-globe-borders.mjs — do not edit by hand.
// Country borders from Natural Earth 110m (public domain, via world-atlas),
// keyed by gazetteer ISO2; "_other" holds land that is not a gazetteer
// country (Antarctica, Greenland, …). Each polygon is [outerRing, ...holes],
// each ring a list of [lng, lat].
export const COUNTRY_BORDERS = ${JSON.stringify(payload)};
`;
writeFileSync(path.join(root, "src/lib/wikido/globe/borders.js"), file);
console.log(`matched ${Object.keys(out).length - 0} countries, ${other.length} other features, ${(file.length / 1024).toFixed(0)} KB`);
if (gaps.length) console.log("gazetteer countries WITHOUT borders:", gaps.join(", "));
